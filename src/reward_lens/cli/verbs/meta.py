"""The two regular utility leaves kept out of the concise root help body."""

from __future__ import annotations

from importlib.metadata import version as installed_version

import click
from click.shell_completion import get_completion_class

from .. import registry


@click.command("version", short_help=registry.SUMMARIES["version"])
def version() -> None:
    """Print the installed reward-lens version."""
    click.echo(f"{registry.PROG} {installed_version('reward-lens')}")


@click.command("completion", short_help=registry.SUMMARIES["completion"])
@click.argument("shell", type=click.Choice(("bash", "zsh", "fish")))
def completion(shell: str) -> None:
    """Print shell completion source generated by Click."""
    from ..main import cli

    completion_class = get_completion_class(shell)
    if completion_class is None:  # click.Choice keeps this unreachable for user input
        raise click.UsageError(f"unsupported shell: {shell}")
    click.echo(
        completion_class(
            cli,
            {},
            registry.PROG,
            "_REWARD_LENS_COMPLETE",
        ).source(),
        nl=False,
    )
